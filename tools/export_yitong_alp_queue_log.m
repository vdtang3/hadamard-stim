function export_yitong_alp_queue_log(out_file)
%EXPORT_YITONG_ALP_QUEUE_LOG Write Yitong's queue-loader ALP calls as text.
%
%   export_yitong_alp_queue_log(out_file)
%
%   Luminos's ALP queue loader is tested off-rig against the calls Yitong's
%   load_sequence_multi made, as recorded in tests/fixtures/yitong_trace.mat.
%   Luminos must not depend on this repository, so the calls are exported
%   once, as plain text, into Luminos's test fixtures.
%
%   Each ALPTool wrapper call is written as the ALP C function it reaches
%   (see "General Matlab/VIALUX control/ALPTool"). Two translations:
%     - device.cleanup is AlpDevHalt followed by AlpSeqFree on every
%       sequence the device holds. That depends on what was loaded before,
%       so it is written as "DevHalt" and "FreeHeld".
%     - alpsequence.put first inquires ALP_DATA_FORMAT to size its buffer.
%       That inquiry is internal to the wrapper and is not written.
%   Sequence calls carry the sequence's 1-based position in its load.

trace_file = fullfile(repo_root(), "tests", "fixtures", "yitong_trace.mat");
trace = load(trace_file, "acquisitions", "provenance");
stim = trace.acquisitions([trace.acquisitions.kind] == "stimulation");

loads = struct("name", {}, "acquisition", {});
first_sparse = find(arrayfun(@(s) s.queue.n_sequences == 30 && ~isempty(s.alp_calls), stim), 1);
first_hadamard = find(arrayfun(@(s) s.queue.n_sequences == 8 && ~isempty(s.alp_calls), stim), 1);
loads(end+1) = struct("name", "sparse", "acquisition", stim(first_sparse));
loads(end+1) = struct("name", "hadamard", "acquisition", stim(first_hadamard));

lines = [
    "# Yitong Qi's load_sequence_multi, as the ALP C calls it made."
    "# Generated by hadamard-stim tools/export_yitong_alp_queue_log.m; do not edit."
    "# hadamard-stim commit: " + git_commit()
    "# source fixture: tests/fixtures/yitong_trace.mat sha256 " + file_sha256(trace_file)
    "# fixture generated from hadamard-stim commit " + trace.provenance.hadamard_stim_git.commit
    ];
for load_ = loads
    a = load_.acquisition;
    lines(end+1, 1) = sprintf("load %s folder=%s sequences=%d", load_.name, a.folder, a.queue.n_sequences); %#ok<AGROW>
    lines = [lines; translate(a.alp_calls)]; %#ok<AGROW>
    lines(end+1, 1) = "end"; %#ok<AGROW>
end
writelines(lines, out_file);
end

function lines = translate(calls)
lines = strings(0, 1);
for c = calls
    args = c.args;
    switch c.op
        case "device.cleanup"
            lines(end+1, 1) = "DevHalt"; %#ok<AGROW>
            lines(end+1, 1) = "FreeHeld"; %#ok<AGROW>
        case "device.projcontrol"
            lines(end+1, 1) = join(["ProjControl" numbers(args)]); %#ok<AGROW>
        case "alpsequence"
            % Constructing the wrapper object makes no ALP call.
        case "seq.alloc"
            lines(end+1, 1) = join(["SeqAlloc" numbers(args)]); %#ok<AGROW>
        case "seq.control"
            lines(end+1, 1) = join(["SeqControl" numbers(args)]); %#ok<AGROW>
        case "seq.timing"
            lines(end+1, 1) = join(["SeqTiming" numbers(args)]); %#ok<AGROW>
        case "seq.inquire"
            lines(end+1, 1) = join(["SeqInquire" numbers(args)]); %#ok<AGROW>
        case "seq.put"
            % args: id, offset, picnum, size, class, sha256. The bytes sent
            % are what matters to the ALP, not MATLAB's array shape.
            lines(end+1, 1) = join(["SeqPut" numbers(args(1:3)) string(prod(args{4}))]); %#ok<AGROW>
        case "device.start"
            lines(end+1, 1) = join(["ProjStart" numbers(args)]); %#ok<AGROW>
        case "device.projinquire"
            lines(end+1, 1) = join(["ProjInquire" numbers(args)]); %#ok<AGROW>
        otherwise
            error("export_yitong_alp_queue_log:UnknownCall", ...
                "No ALP translation for %s.", c.op);
    end
end
end

function s = numbers(args)
s = cellfun(@(v) string(v), args);
end

function root = repo_root()
root = fileparts(fileparts(mfilename("fullpath")));
end

function commit = git_commit()
[status, out] = system(sprintf('git -C "%s" rev-parse HEAD', repo_root()));
commit = "unknown";
if status == 0
    commit = strtrim(string(out));
end
[~, porcelain] = system(sprintf('git -C "%s" status --porcelain', repo_root()));
if strlength(strtrim(string(porcelain))) > 0
    commit = commit + " (dirty)";
end
end

function hex = file_sha256(file)
fid = fopen(file, "r");
closer = onCleanup(@() fclose(fid));
md = java.security.MessageDigest.getInstance("SHA-256");
md.update(typecast(fread(fid, inf, "*uint8"), "int8"));
hex = string(lower(reshape(dec2hex(typecast(md.digest(), "uint8"), 2).', 1, [])));
end
